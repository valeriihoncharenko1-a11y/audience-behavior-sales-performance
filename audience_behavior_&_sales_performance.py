# Checking whether the difference in traffic between devices is statistically significant
df['has_purchase_flag'] = df['price'].notna().astype(int)


device_stats = (
    df.groupby('device')
    .agg(
        sessions=('ga_session_id', 'count'),
        purchases=('has_purchase_flag', 'sum'),
    )
    .reset_index()
)

devices = device_stats['device'].tolist()


for i in range(len(devices)):
  for j in range(i + 1, len(devices)):
    dev_a = devices[i]
    dev_b = devices[j]

    row_a = device_stats[device_stats['device'] == dev_a].iloc[0]
    sessions_a = row_a['sessions']
    purchases_a = row_a['purchases']

    row_b = device_stats[device_stats['device'] == dev_b].iloc[0]
    sessions_b = row_b['sessions']
    purchases_b = row_b['purchases']


    z_stat, p_value = sm.stats.proportions_ztest(
        [purchases_a, purchases_b], [sessions_a, sessions_b]
    )

    print(f'{dev_a} vs {dev_b}')
    print(f'P-value: {p_value}')

    if p_value < 0.05:
      print('The difference is statistically significant.\n')
    else:
      print('The difference is random and is not statistically significant.\n')

"""The proportion test did not identify a statistically significant difference in purchasing-session proportions between the tested devices."""

